# logger.py используется для того, чтобы настроить логирование один раз и 
# использовать готовый логгер во всех остальных модулях. Благодаря этому в 
# консоли видно, что происходит с ботом (кто нажал кнопку, что ответил бот, 
#где произошла ошибка), а не приходится расставлять print() по всему проекту. 
# Папка utils — это «инструменты»:вспомогательные функции, не относящиеся 
# напрямую к логике бота.


# Что это значит на практике:

# Добавил новую команду, но не вписал logger.info(...) в её обработчик → 
# в консоли про неё ничего не появится.

# Вписал logger.info(f"Пользователь {message.from_id} нажал {message.text}") → 
# появится ровно эта строка с временем.

import logging

def setup_logger():
    """Настраивает логгер для бота"""
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
        datefmt="%H:%M:%S"
    )
    return logging.getLogger("vk_bot")

# Создаём логгер
logger = setup_logger()
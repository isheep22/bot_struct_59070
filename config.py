# config.py используется для того, чтобы загружать секреты (токен бота) из файла
# .env и хранить глобальные настройки проекта в одном месте. Благодаря этому токен
# не попадает в исходный код и не утекает в Git, а если он поменяется — править нужно
# только .env, а не искать токен по всему проекту.


import os
from dotenv import load_dotenv

# Загружаем переменные из .env
load_dotenv()

# Токен бота
BOT_TOKEN = os.getenv("MY_TOKEN")

# Проверка, что токен загружен
if not BOT_TOKEN:
    raise ValueError("❌ Токен не найден! Проверь файл .env")


